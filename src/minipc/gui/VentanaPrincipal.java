    private void actualizarTablaInstrucciones(){
        String[] columnas = {"Instrucción", "Binario"};
        Object[][] datos = new Object[instruccionesActuales.size()][2];

        for(int i = 0; i < instruccionesActuales.size(); i++){
            Instruccion instr = instruccionesActuales.get(i);

            String textoInstruccion = instr.getoperacion() + " " + instr.getregistro();
            if(instr.getvalor() != null){
                textoInstruccion = textoInstruccion + ", " + instr.getvalor();
            }

            String textoBinario = instr.getcodigoBinarioOperacion();
            if(instr.getcodigoBinarioValor() != null){
                textoBinario = textoBinario + " " + instr.getcodigoBinarioValor();
            }

            datos[i][0] = textoInstruccion;
            datos[i][1] = textoBinario;
        }

        DefaultTableModel modelo = new DefaultTableModel(datos, columnas);
        tablaInstrucciones.setModel(modelo);
    }
    
    private void actualizarTablaMemoria(){
        String[] columnas = {"Posición", "Valor en memoria"};
        String[] todaLaMemoria = memoria.getTodasLasPosiciones();
        Object[][] datos = new Object[todaLaMemoria.length][2];

        // Mapa: posición -> texto de instrucción
        String[] textoEnPosicion = new String[todaLaMemoria.length];
        int posicionActual = memoria.getInicioUsuario();
        for(int i = 0; i < instruccionesActuales.size(); i++){
            Instruccion instr = instruccionesActuales.get(i);
            String textoInstruccion = instr.getoperacion() + " " + instr.getregistro();
            if(instr.getvalor() != null){
                textoInstruccion = textoInstruccion + ", " + instr.getvalor();
            }
            textoEnPosicion[posicionActual] = textoInstruccion;
            posicionActual = posicionActual + 1;
        }

        for(int i = 0; i < todaLaMemoria.length; i++){
            datos[i][0] = i;
            if(textoEnPosicion[i] != null){
                datos[i][1] = textoEnPosicion[i];
            } else {
                datos[i][1] = "";
            }
        }

        DefaultTableModel modelo = new DefaultTableModel(datos, columnas);
        tablaMemoria.setModel(modelo);
    }
