    private void btnAsignarMemoriaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAsignarMemoriaActionPerformed
        if(cpu != null && !cpu.programaTerminado()){
            JOptionPane.showMessageDialog(this, "No se puede asignar memoria mientras un programa está en ejecución. Terminá la ejecución o dale a Limpiar primero.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String textoTotal = txtTamanoTotal.getText().trim();
        String textoSistema = txtTamanoSistema.getText().trim();

        int tamanoTotal;
        int tamanoSistema;

        try {
            tamanoTotal = Integer.parseInt(textoTotal);
            tamanoSistema = Integer.parseInt(textoSistema);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Los tamaños deben ser números enteros", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if(tamanoTotal < 256){
            JOptionPane.showMessageDialog(this, "El tamaño total debe ser de al menos 256", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if(tamanoSistema < 64 || tamanoSistema >= tamanoTotal){
            JOptionPane.showMessageDialog(this, "El tamaño del S.O. debe ser de al menos 64 y menor al tamaño total", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        cpu = null;
        memoria = null;
        bcp = null;
        instruccionesActuales = null;

        lblValorPC.setText("0");
        lblValorIR.setText("");
        lblValorAC.setText("0");
        lblValorAX.setText("0");
        lblValorBX.setText("0");
        lblValorCX.setText("0");
        lblValorDX.setText("0");

        DefaultTableModel modeloVacioInstrucciones = new DefaultTableModel(new Object[0][2], new String[]{"Instrucción", "Binario"});
        tablaInstrucciones.setModel(modeloVacioInstrucciones);

        DefaultTableModel modeloVacioMemoria = new DefaultTableModel(new Object[0][2], new String[]{"Posición", "Valor en memoria"});
        tablaMemoria.setModel(modeloVacioMemoria);
        
        memoria = new Memoria(tamanoTotal, tamanoSistema);
        cpu = new CPU(memoria);
        instruccionesActuales = null;
        bcp = null;
        
                



        JOptionPane.showMessageDialog(this, "Memoria asignada: " + tamanoTotal + " posiciones, " + tamanoSistema + " para el S.O.", "Memoria asignada", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnAsignarMemoriaActionPerformed

